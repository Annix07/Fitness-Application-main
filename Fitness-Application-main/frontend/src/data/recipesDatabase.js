// Helper to scale recipe nutrients for custom servings (0.5x, 1x, 2x, etc.)
export function scaleRecipeNutrients(recipe, servings = 1) {
  if (!recipe || servings <= 0) return { calories: 0, protein: 0, carbs: 0, fat: 0, fiber: 0 };
  const mult = servings / (recipe.servings || 1);
  return {
    calories: Math.round(recipe.calories * mult),
    protein: parseFloat((recipe.protein * mult).toFixed(1)),
    carbs: parseFloat((recipe.carbs * mult).toFixed(1)),
    fat: parseFloat((recipe.fat * mult).toFixed(1)),
    fiber: parseFloat(((recipe.fiber || 0) * mult).toFixed(1)),
  };
}
