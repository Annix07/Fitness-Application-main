// Helper to compute exact nutritional values for any specified quantity & unit
export function calculateNutrients(foodItem, quantity, unit = 'g') {
  if (!foodItem || !quantity || Number(quantity) <= 0) {
    return { calories: 0, protein: 0, carbs: 0, fat: 0 };
  }

  const numQty = parseFloat(quantity) || 0;
  let multiplier = 1;
  if (unit === 'serving') {
    multiplier = numQty;
  } else {
    // gram / ml basis (per 100g/ml or base servingSize)
    multiplier = numQty / (foodItem.servingSize || 100);
  }

  return {
    calories: Math.round((foodItem.calories || 0) * multiplier),
    protein: parseFloat(((foodItem.protein || 0) * multiplier).toFixed(1)),
    carbs: parseFloat(((foodItem.carbs || 0) * multiplier).toFixed(1)),
    fat: parseFloat(((foodItem.fat || 0) * multiplier).toFixed(1)),
  };
}

